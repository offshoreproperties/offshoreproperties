/**
 * Regenerate hero slideshow from kenya-gallery.allowlist.json
 * Edit src/lib/kenya-gallery.allowlist.json — only listed files appear on the homepage.
 * Run: npm run sync:gallery
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "public", "kenya");
const allowlistPath = join(root, "src", "lib", "kenya-gallery.allowlist.json");
const out = join(root, "src", "lib", "kenya-gallery.generated.ts");

if (!existsSync(allowlistPath)) {
  console.error("Missing src/lib/kenya-gallery.allowlist.json");
  process.exit(1);
}

const allowlist = JSON.parse(readFileSync(allowlistPath, "utf8"));
if (!Array.isArray(allowlist)) {
  console.error("Allowlist must be a JSON array of filenames");
  process.exit(1);
}

const urls = [];
const missing = [];

for (const name of allowlist) {
  const filePath = join(dir, name);
  if (existsSync(filePath)) {
    urls.push(`/kenya/${name}`);
  } else {
    missing.push(name);
  }
}

if (missing.length) {
  console.warn("Allowlisted but missing from public/kenya:");
  missing.forEach((n) => console.warn(`  - ${n}`));
}

writeFileSync(
  out,
  `/** Auto-generated by scripts/sync-kenya-gallery.mjs from kenya-gallery.allowlist.json */\nexport const KENYA_GALLERY_IMAGES = ${JSON.stringify(urls, null, 2)} as const;\nexport const KENYA_GALLERY_CACHE_KEY = ${JSON.stringify(urls.join("|"))};\n`,
);

console.log(`Kenya gallery: ${urls.length} image(s) in slideshow`);
urls.forEach((u) => console.log(`  ${u}`));
