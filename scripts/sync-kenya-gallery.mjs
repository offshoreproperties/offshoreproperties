/**
 * Regenerate hero slideshow from kenya-gallery.allowlist.json
 * ONLY files in public/kenya/ that are explicitly allowlisted appear on the homepage.
 * Run: npm run sync:gallery
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "public", "kenya");
const allowlistPath = join(root, "src", "lib", "kenya-gallery.allowlist.json");
const out = join(root, "src", "lib", "kenya-gallery.generated.ts");

if (!existsSync(allowlistPath)) {
  console.error("Missing src/lib/kenya-gallery.allowlist.json");
  process.exit(1);
}

const allowlist = JSON.parse(readFileSync(allowlistPath, "utf8"));
if (!Array.isArray(allowlist)) {
  console.error("Allowlist must be a JSON array of filenames");
  process.exit(1);
}

const urls = [];
const missing = [];
const invalid = [];

for (const raw of allowlist) {
  const name = basename(String(raw).trim());
  if (!name || name !== raw || name.includes("..")) {
    invalid.push(String(raw));
    continue;
  }
  const filePath = join(dir, name);
  if (existsSync(filePath)) {
    urls.push(`/kenya/${name}`);
  } else {
    missing.push(name);
  }
}

if (invalid.length) {
  console.error("Invalid allowlist entries (must be filenames inside public/kenya only):");
  invalid.forEach((n) => console.error(`  - ${n}`));
  process.exit(1);
}

if (missing.length) {
  console.warn("Allowlisted but missing from public/kenya (skipped on homepage):");
  missing.forEach((n) => console.warn(`  - ${n}`));
}

if (existsSync(dir)) {
  const onDisk = readdirSync(dir).filter((f) => !f.startsWith("."));
  const notListed = onDisk.filter((f) => !allowlist.includes(f));
  if (notListed.length) {
    console.warn("In public/kenya but NOT on homepage allowlist:");
    notListed.forEach((n) => console.warn(`  - ${n}`));
  }
}

writeFileSync(
  out,
  `/** Auto-generated by scripts/sync-kenya-gallery.mjs from kenya-gallery.allowlist.json */\nexport const KENYA_GALLERY_IMAGES = ${JSON.stringify(urls, null, 2)} as const;\nexport const KENYA_GALLERY_CACHE_KEY = ${JSON.stringify(urls.join("|"))};\n`,
);

console.log(`Kenya gallery: ${urls.length} image(s) in slideshow`);
urls.forEach((u) => console.log(`  ${u}`));
